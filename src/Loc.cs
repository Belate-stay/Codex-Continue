    public static void Set(Lang lang)
    {
        Current = lang;
    }

    /// <summary>Resolve the effective language (system → OS culture).</summary>
    public static bool IsZh() => Current switch
    {
        Lang.Zh => true,
        Lang.En => false,
        _ => CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.Equals("zh", StringComparison.OrdinalIgnoreCase),
    };

    public static string T(string key, params object[] args)
    {
        var dict = IsZh() ? Zh : En;
        if (!dict.TryGetValue(key, out var s)) return key;
        return args.Length == 0 ? s : string.Format(s, args);
    }
